// Regenerates the checklist table at the end of backend/seed/PROGRESS.md from the actual files:
//   VERIFIED  verified.json has the current sha256 of problems/<slug>.json
//   BLOCKED   listed in blocked.json (with the error and what was tried)
//   FAILED    built and verified, but the last verification failed
//   BUILT     problems/<slug>.json exists, not verified yet
//   todo      nothing built yet
// Usage (from backend/): node seed/tools/progress.js
const fs = require("fs");
const path = require("path");
const P = require("./lib/problems");

const MARK = "## Checklist";
const progressFile = path.join(P.paths.seed, "PROGRESS.md");
const blocked = P.readJson(path.join(P.paths.seed, "blocked.json"), {});
const verified = P.readJson(P.paths.verified, {});
const results = P.readJson(P.paths.results, {});
const batches = P.readJson(P.paths.batches, {});
const batchOf = {};
for (const [n, slugs] of Object.entries(batches)) for (const s of slugs) batchOf[s] = n;

const statusOf = (slug) => {
  if (blocked[slug]) return "BLOCKED";
  const file = P.paths.problem(slug);
  if (!fs.existsSync(file)) return "todo";
  if (verified[slug] && verified[slug].sha256 === P.fileHash(file)) return "VERIFIED";
  if (results[slug] && !results[slug].ok) return "FAILED";
  return "BUILT";
};

const list = P.loadList();
const counts = {};
const rows = list.map((p) => {
  const status = statusOf(p.slug);
  counts[status] = (counts[status] || 0) + 1;
  const note = blocked[p.slug]?.error || (results[p.slug]?.errors || [])[0] || "";
  return `| ${p.order} | ${p.slug} | ${p.title} | ${p.difficulty} | ${p.topic} | ${batchOf[p.slug] || ""} | ${status} | ${String(note).replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 160)} |`;
});

const text = fs.readFileSync(progressFile, "utf8");
const head = text.slice(0, text.indexOf(MARK));
const body = [
  MARK,
  "Generated by `node seed/tools/progress.js` from the files on disk. Statuses: VERIFIED (current file passed",
  "verify.js), BUILT (not verified yet), FAILED (last verification failed), BLOCKED (see blocked.json), todo.",
  "",
  `**Totals:** ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ")} (of ${list.length})`,
  "",
  "| # | Slug | Title | Difficulty | Topic | Batch | Status | Notes |",
  "|---|---|---|---|---|---|---|---|",
  ...rows,
].join("\n");
fs.writeFileSync(progressFile, head + body + "\n");
